#!/usr/bin/env node

import { execSync, spawn } from 'child_process';
import fs from 'fs';
import path from 'path';

console.log('🔍 Checking local Supabase status...');

let isRunning = false;
try {
  execSync('supabase status', { stdio: 'ignore' });
  isRunning = true;
} catch {
  isRunning = false;
}

if (!isRunning) {
  console.log('🚀 Local Supabase is not running. Booting containers & applying snapshot...');
  try {
    execSync('node --env-file=.env supabase/scripts/clone.mjs', { stdio: 'inherit' });
  } catch {
    console.error('\n❌ Could not start local Supabase.');
    console.error('👉 Ensure Docker Desktop or OrbStack is running on your Mac, then run this command again.');
    process.exit(1);
  }
} else {
  console.log('⚡ Local Supabase is already running.');
}

// Ensure .env.local is in place so frontend talks to local clone
const localEnvPath = path.resolve('.env.local');
const localAnonKey =
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJpYXQiOjE2NDk5MjA4MDAsImV4cCI6MTk2NTQ5NjgwMH0.18B0mzQ1s4q2E8s51iN6w_Kj3m7wW-4t7Y8Z9a0b1c2';

if (!fs.existsSync(localEnvPath)) {
  const localEnvContent = `# Auto-generated by yarn dev:local (Points frontend to local Supabase clone)
VITE_SUPABASE_URL=http://127.0.0.1:54321
VITE_SUPABASE_ANON_KEY=${localAnonKey}
VITE_SUPABASE_PUBLISHABLE_KEY=${localAnonKey}
VITE_APP_URL=http://localhost:5173
`;
  fs.writeFileSync(localEnvPath, localEnvContent, 'utf-8');
}

console.log('\n======================================================');
console.log('🚀 MOCKSIGNAL FULLSTACK ENVIRONMENT READY');
console.log('======================================================');
console.log('🌐 Web App:         http://localhost:5173');
console.log('🛠️  Supabase Studio: http://127.0.0.1:54323 (View tables & data)');
console.log('📬 Inbucket Mailbox: http://127.0.0.1:54324 (Test emails)');
console.log('======================================================\n');
console.log('Starting Vite development server...\n');

// Spawn Vite in foreground with full interactive terminal stdio
const vite = spawn('npx', ['vite'], { stdio: 'inherit', shell: true });

vite.on('exit', (code) => {
  process.exit(code ?? 0);
});
