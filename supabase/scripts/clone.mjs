#!/usr/bin/env node

import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';

const skipSnapshot = process.argv.includes('--no-snapshot') || process.argv.includes('--skip-snapshot');

// -------------------------------------------------------------
// Step 1: Capture latest production data snapshot
// -------------------------------------------------------------
if (!skipSnapshot) {
  console.log('📦 Step 1/3: Attempting to pull latest snapshot from production...');
  try {
    execSync('node --env-file=.env supabase/scripts/snapshot.mjs', { stdio: 'inherit' });
  } catch {
    console.log('\n⚠️  Could not fetch live snapshot (requires `supabase login`).');
    if (fs.existsSync(path.resolve('supabase/seed.sql'))) {
      console.log('ℹ️  Proceeding with previously saved local snapshot in `supabase/seed.sql`.');
    } else {
      console.log('ℹ️  Proceeding with clean database baseline (no seed file found).');
    }
  }
} else {
  console.log('⏭️  Skipping production snapshot (--no-snapshot flag detected).');
}

// -------------------------------------------------------------
// Step 2: Start local Supabase Docker containers
// -------------------------------------------------------------
console.log('\n🚀 Step 2/3: Starting local Supabase development environment...');
try {
  execSync('supabase start', { stdio: 'inherit' });
} catch {
  console.error('\n❌ Failed to start Supabase.');
  console.error('👉 If Docker/Colima is running, check the terminal output above for specific database or seed errors.');
  process.exit(1);
}

// -------------------------------------------------------------
// Step 3: Replay migrations & load latest snapshot
// -------------------------------------------------------------
console.log('\n🔄 Step 3/3: Replaying all migrations and loading snapshot into local clone...');
try {
  execSync('supabase db reset', { stdio: 'inherit' });
} catch {
  console.error('\n❌ Failed to replay migrations on local Supabase.');
  process.exit(1);
}

// -------------------------------------------------------------
// Step 4: Configure local frontend environment (.env.local) dynamically
// -------------------------------------------------------------
let localApiUrl = 'http://127.0.0.1:54321';
let localAnonKey = '';

try {
  const statusOutput = execSync('supabase status -o json', { stdio: 'pipe' }).toString();
  const jsonStart = statusOutput.indexOf('{');
  const jsonEnd = statusOutput.lastIndexOf('}');
  if (jsonStart !== -1 && jsonEnd !== -1) {
    const status = JSON.parse(statusOutput.slice(jsonStart, jsonEnd + 1));
    if (status.API_URL) localApiUrl = status.API_URL;
    if (status.ANON_KEY) localAnonKey = status.ANON_KEY;
  }
} catch {
  // Graceful fallback if status json output cannot be read
}

const localEnvPath = path.resolve('.env.local');
const localEnvContent = `# Auto-generated by yarn db:clone (Points frontend to local Supabase clone)
VITE_SUPABASE_URL=${localApiUrl}
VITE_SUPABASE_ANON_KEY=${localAnonKey}
VITE_SUPABASE_PUBLISHABLE_KEY=${localAnonKey}
VITE_APP_URL=http://localhost:5173
`;

fs.writeFileSync(localEnvPath, localEnvContent, 'utf-8');

console.log('\n======================================================');
console.log('🎉 LOCAL PRODUCTION CLONE IS READY & RUNNING!');
console.log('======================================================');
console.log('🌐 Supabase Studio UI:  http://127.0.0.1:54323  (View all tables & data)');
console.log('📬 Inbucket Local Mail: http://127.0.0.1:54324  (Test emails & magic links)');
console.log('⚡ Local API Gateway:   http://127.0.0.1:54321');
console.log('🐘 Local PostgreSQL:    postgresql://postgres:postgres@127.0.0.1:54322/postgres');
console.log('======================================================');
console.log('\n👉 Next steps:');
console.log('1. Run `yarn dev` to start your web app pointing at this local clone.');
console.log('2. Open `http://127.0.0.1:54323` to browse or test SQL queries.');
console.log('3. When finished, run `yarn db:stop` and `rm .env.local` to return to prod.');
console.log('======================================================\n');
